<?php

// REST API routes for every table in the database, plus AI gift suggestions.
// Everything in this file is automatically prefixed with /api (see bootstrap/app.php).
//
// Each apiResource() registers the 5 standard REST routes, e.g. for products:
//   GET    /api/products             index    paginated list
//   POST   /api/products             store    create            (201 Created)
//   GET    /api/products/{product}   show     one record        (404 if the ID doesn't exist)
//   PUT    /api/products/{product}   update   change fields     (PATCH works too)
//   DELETE /api/products/{product}   destroy  delete            (204 No Content)
// Run `php artisan route:list --path=api` to see them all.

use App\Http\Controllers\Api\CartController;
use App\Http\Controllers\Api\CartItemController;
use App\Http\Controllers\Api\CategoryController;
use App\Http\Controllers\Api\GiftSuggestionController;
use App\Http\Controllers\Api\OrderController;
use App\Http\Controllers\Api\OrderItemController;
use App\Http\Controllers\Api\ProductController;
use App\Http\Controllers\Api\UserController;
use Illuminate\Support\Facades\Route;

Route::apiResources([
    'products' => ProductController::class,
    'categories' => CategoryController::class,
    'users' => UserController::class,
    'carts' => CartController::class,
    'cart-items' => CartItemController::class,
    'orders' => OrderController::class,
    'order-items' => OrderItemController::class,
]);

// AI bonus: gift suggestions generated by an LLM from the cart's contents.
Route::get('carts/{cart}/gift-suggestions', [GiftSuggestionController::class, 'show'])->name('carts.gift-suggestions');
